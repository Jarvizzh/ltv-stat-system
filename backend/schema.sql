-- 1. 落地页 ID 配置表
CREATE TABLE IF NOT EXISTS `landing_page_config` (
  `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
  `landing_page_id` VARCHAR(64) NOT NULL UNIQUE,
  `sync_status` VARCHAR(20) DEFAULT 'COMPLETED',
  `last_sync_time` DATETIME DEFAULT NULL,
  `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP,
  `updated_at` DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- 2. 订单明细表 (含美东时间转换)
CREATE TABLE IF NOT EXISTS `raw_order` (
  `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
  `order_id` VARCHAR(64) NOT NULL UNIQUE,
  `member_id` VARCHAR(64) NOT NULL,
  `landing_page_id` VARCHAR(64) DEFAULT NULL,
  `register_time_bj` DATETIME NOT NULL,
  `register_time_et` DATETIME NOT NULL,
  `register_date_et` DATE NOT NULL,
  `pay_time_bj` DATETIME NOT NULL,
  `pay_time_et` DATETIME NOT NULL,
  `pay_date_et` DATE NOT NULL,
  `order_amount_cent` INT NOT NULL,
  `order_amount_usd` DECIMAL(10,2) NOT NULL,
  `is_subs` INT DEFAULT 0,
  `renew_type` INT DEFAULT 1,
  `pay_state` INT DEFAULT 1,
  `refund_status` INT DEFAULT 0,
  `created_at` DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- 3. 投放消耗与备注配置表
CREATE TABLE IF NOT EXISTS `ltv_launch_config` (
  `launch_date` DATE PRIMARY KEY,
  `spend` DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  `remark` VARCHAR(500) DEFAULT '',
  `updated_at` DATETIME DEFAULT CURRENT_TIMESTAMP
);

