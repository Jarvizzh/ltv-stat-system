-- 6. LTV 预测基准数据表 (形态 B)
CREATE TABLE IF NOT EXISTS `ltv_predict_benchmark` (
  `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
  `dimension_type` VARCHAR(32) NOT NULL DEFAULT 'ALL',
  `dimension_value` VARCHAR(64) NOT NULL DEFAULT 'DEFAULT',
  `sub_period_days` INT NOT NULL DEFAULT 1,
  `day_index` INT NOT NULL,
  `base_retention_rate` DECIMAL(10,6) NOT NULL DEFAULT 0.000000,
  `base_arpu` DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  `sample_cohort_count` INT NOT NULL DEFAULT 0,
  `is_extrapolated` INT NOT NULL DEFAULT 0,
  `updated_at` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY `uk_dim_period_day` (`dimension_type`, `dimension_value`, `sub_period_days`, `day_index`)
);

-- 7. 订阅配置与落地页版本快照表
CREATE TABLE IF NOT EXISTS `subscription_config_version` (
  `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
  `landing_page_id` VARCHAR(64) NOT NULL,
  `subscribe_config_id` VARCHAR(64) NOT NULL,
  `subscribe_config_name` VARCHAR(128) DEFAULT '',
  `sale_combo_id` VARCHAR(64) DEFAULT NULL,
  `sale_combo_name` VARCHAR(128) DEFAULT '',
  `product_id` VARCHAR(64) NOT NULL,
  `product_name` VARCHAR(128) DEFAULT '',
  `sub_period_days` INT NOT NULL DEFAULT 1,
  `first_price_cent` INT NOT NULL,
  `renew_price_cent` INT NOT NULL,
  `version_num` INT NOT NULL DEFAULT 1,
  `effective_start_time` DATETIME NOT NULL,
  `effective_end_time` DATETIME DEFAULT NULL,
  `updated_at` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_pid_first_price` (`landing_page_id`, `first_price_cent`, `effective_start_time`)
);

-- 8. 用户-订阅周期与配置关联表
CREATE TABLE IF NOT EXISTS `user_subscription_period` (
  `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
  `member_id` VARCHAR(64) NOT NULL UNIQUE,
  `landing_page_id` VARCHAR(64) DEFAULT NULL,
  `subscribe_config_id` VARCHAR(64) DEFAULT NULL,
  `sub_period_days` INT NOT NULL DEFAULT 1,
  `first_price_cent` INT DEFAULT NULL,
